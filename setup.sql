CREATE DATABASE IF NOT EXISTS DIAMOND_PRICE_ML;

CREATE SCHEMA IF NOT EXISTS DIAMOND_PRICE_ML.ML_WORKFLOW;

CREATE WAREHOUSE IF NOT EXISTS DIAMOND_ML_WH
    WAREHOUSE_SIZE = 'X-SMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE;

USE DATABASE DIAMOND_PRICE_ML;
USE SCHEMA ML_WORKFLOW;
USE WAREHOUSE DIAMOND_ML_WH;

-- Raw dataset table
-- Dataset loaded into:
-- DIAMOND_PRICE_ML.ML_WORKFLOW.DIAMONDS_RAW

-- Create train/test split
CREATE OR REPLACE TABLE DIAMOND_PRICE_ML.ML_WORKFLOW.DIAMONDS_SPLIT AS
SELECT
    *,
    UNIFORM(0, 1, RANDOM(42)) AS SPLIT_VALUE
FROM DIAMOND_PRICE_ML.ML_WORKFLOW.DIAMONDS_RAW;

-- Training dataset
CREATE OR REPLACE TABLE DIAMOND_PRICE_ML.ML_WORKFLOW.DIAMONDS_TRAIN AS
SELECT *
FROM DIAMOND_PRICE_ML.ML_WORKFLOW.DIAMONDS_SPLIT
WHERE SPLIT_VALUE < 0.80;

-- Testing dataset
CREATE OR REPLACE TABLE DIAMOND_PRICE_ML.ML_WORKFLOW.DIAMONDS_TEST AS
SELECT *
FROM DIAMOND_PRICE_ML.ML_WORKFLOW.DIAMONDS_SPLIT
WHERE SPLIT_VALUE >= 0.80;
